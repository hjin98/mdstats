"""Finite periodic-net automorphism groups modulo lattice translations.

This module assembles the subgroup generated by explicitly supplied, already
validated :class:`~mdstats.analysis.ValidatedPeriodicAutomorphism` records.  Each
operation belongs to one immutable :class:`~mdstats.analysis.PeriodicNetView`.
Representatives are normalized by removing a common lattice translation at one
deterministic source anchor vertex.

The periodic quotient/vector representation follows Chung, Hahn, and Klee
(1984).  Exact combinatorial periodic-net automorphisms and finite
representatives modulo translations follow Delgado-Friedrichs and O'Keeffe
(2003).  mdstats adds deterministic source binding, explicit multiedge action,
and transactional finite closure. Primitive-ring actions remain in a separate, source-bound derived index.

This module does not discover generators automatically and does not compute a
Euclidean space group.

References
----------
S. J. Chung, Th. Hahn, and W. E. Klee, Acta Cryst. A 40, 42-50 (1984),
doi:10.1107/S0108767384000088.
O. Delgado-Friedrichs and M. O'Keeffe, Acta Cryst. A 59, 351-360 (2003),
doi:10.1107/S0108767303012017.
"""

